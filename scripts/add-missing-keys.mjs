const newKeys = Object.fromEntries(
  Object.entries(values).map(([locale, strings]) => {
    if (strings.length !== keys.length) throw new Error(`Incomplete translations: ${locale}`)
    return [locale, Object.fromEntries(keys.map((key, i) => [key, strings[i]]))]
  })
)
// Update only these keys; all existing translations and locale-specific additions are retained.
for (const [locale, additions] of Object.entries(newKeys)) {
  const path = `i18n/locales/${locale}.json`
  const original = JSON.parse(await fs.readFile(path, 'utf8'))
  const sorted = Object.fromEntries(
    Object.entries({ ...original, ...additions }).sort(([a], [b]) => a.localeCompare(b, 'en'))
  )
  await fs.writeFile(path, JSON.stringify(sorted, null, '\t') + '\n')
}
// Preserve the Excel source so pnpm i18n:write does not remove the new strings.
const workbook = XLSX.readFile('i18n/i18n.xlsx')
const sheet = workbook.Sheets.Sheet1
const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: '' })
const header = rows[0]
for (const key of keys) {
  let row = rows.find((r, i) => i && r[0] === key)
  if (!row) {
    row = Array(header.length).fill('')
    row[0] = key
    rows.push(row)
  }
  header.forEach((locale, i) => {
    if (i && newKeys[locale]?.[key]) row[i] = newKeys[locale][key]
  })
}
XLSX.utils.sheet_add_aoa(sheet, rows, { origin: 'A1' })
XLSX.writeFile(workbook, 'i18n/i18n.xlsx')
